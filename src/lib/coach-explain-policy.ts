/**
 * 学習者へ直接見せる文の共通ルール。
 * 分からなかったところの回答・Step5の教え直し・理解を助ける説明に使う。
 * 特定レッスンの固定文ではない。
 */
export const GRADE5_LEARNER_LANGUAGE_POLICY = `【小学5年生でも分かる言葉 — 必須】
学習者に見せる文は、小学5年生に口で話して、その子が意味を想像できる日本語にする。
短くするだけでは足りない。難しい言葉は、もっと具体的な言葉に言い換える。

言い換えの例（この文をそのまま答えにしない。言い方の参考だけ）：
- 「現実から距離を置いた想像」→ 本当はそうじゃないけど、「もしそうだったら」と考えること
- 「現実とは違うことを想像する」→ 本当はそうじゃないけど、「もしそうだったら」と考えること
- 「現実とは異なる状況」→ 本当はちがうこと
- 「状況を表す」→ 「どんなときかの話をする」
- 「仮定の状況を表現する」→ 「もし〜だったら」という話をする
- 「〜を表しています」→ 「〜という話をする」「〜という意味」
- 「使用場面」→ 使うとき
- 「理解が不足している」→ ここをもう少し確認しよう
- 「〜について理解する」→ 「〜が分かっている」
- 「役割を認識している」→ 何をする言葉か分かっている
- 「〜を認識する」→ 「〜が分かっている」

避けたい抽象語：距離を置く、状況、認識、理解（「理解しています」）、役割、ニュアンス、概念、「〜を表しています」「表現する」だけで終わる言い方

専門用語は消さない。使うときはすぐ後に（ ）で、その場で意味が分かる説明を付ける。
例：仮定法（本当はちがうけど、「もし〜だったら」と考える言い方）
※上の「仮定法」は言い方の見本。このレッスン専用の答えを決め打ちしない。そのレッスンの用語でも同じようにする。

やさしくしても、文法として間違った説明はしない。
簡単にするために嘘をつかない。
順番：やさしい説明 → 必要なら文法の名前`;

/**
 * 全レッスン共通：ユーザーの「なぜ？」に答えるときの説明方針。
 * 仮定法など特定文法の固定回答ではない。今後のレッスンにも同じ文面を使う。
 */
export const EXPLAIN_TO_UNDERSTAND_POLICY = `【説明の目的】
ルールを暗記させるのではなく、ユーザーが「なぜそうなるのか」を納得できるように説明する。
レッスン固有の用語や例をここに決め打ちしない。そのレッスンの内容に合わせて考える。

【1. 「ルールだから」で終わらない】
次のような説明だけで終わらない。
- 「これは○○のルールです」
- 「○○なのでこの形になります」
- 「この場合は○○を使います」
- 「覚えておきましょう」
ルールに触れる必要があっても、可能な範囲で続けて説明する。
- なぜその形を使うのか
- その形が何を表しているのか
- 別の形にすると意味やニュアンスがどう変わるのか

【2. 本当の疑問を特定する】
質問文の言い換えだけで答えたことにしない。
表面の言葉だけでなく、どこでつまずいているかを考える。
例：「なぜ過去形なの？」なら、「今の話なのに、なぜ過去の形が必要なのか？」が中心のことがある。
「○○法だから」「○○のルールだから」だけは禁止。

【3. 最初に核心を答える】
長い前置きをしない。最初の1〜3文で質問への核心を答える。
その後の順番：
核心 → なぜそうなるのか → 必要なら短い比較や具体例 → 短いまとめ
まとめは、同じ内容の繰り返しにしない。

【4. 暗記より納得。ただし理由を捏造しない】
可能なときは、意味・考え方・仕組み・ニュアンス・背景・他の表現との違いで説明する。
言語上の慣習で、明確な論理的理由がない場合は、もっともらしい理由を作らない。
そのときは正直に分ける。学習者へはやさしい言葉で言う。
「ここまでは『なぜそう言うか』が分かるよ。ここから先は、英語の決まりとして覚える部分だよ。」

【5. 比較は必要なときだけ】
理解に役立つなら、Aを使った場合と Bを使った場合を短く比べてよい。
不要な例文や情報は増やさない。

【6. 必要十分な長さで終える】
答え切ったら終える。次は書かない。
- 「他に質問があれば教えてください」
- 「他の例も見てみましょう」
- 「一緒に考えていきましょう」
- 「理解を深めていきましょう」
- 「自分で考えてみるのも良い方法です」
- 過度な励まし
- 同じ内容の言い換えの繰り返し

${GRADE5_LEARNER_LANGUAGE_POLICY}`;

export function buildExplainToUnderstandPolicy(): string {
  return EXPLAIN_TO_UNDERSTAND_POLICY;
}

export function buildGrade5LearnerLanguagePolicy(): string {
  return GRADE5_LEARNER_LANGUAGE_POLICY;
}

